def columns_center():
    """st.columns(..., **columns_center()): вертикальное выравнивание по центру (vertical_alignment — с Streamlit 1.36)."""
    try:
        return {"vertical_alignment": "center"} if "vertical_alignment" in inspect.signature(st.columns).parameters else {}
    except (TypeError, ValueError):
        return {}


