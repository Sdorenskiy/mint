def _typed(field, value):
    d = getattr(DEFAULTS, field)
    if isinstance(d, bool):
        return bool(value)
    if isinstance(d, int):
        return int(value)
    if isinstance(d, float):
        return float(value)
    return value


def _slider(label, key, lo, hi, step, default, help_text, on_change=None):
    """Слайдер, который не ломается, если значение по умолчанию вне диапазона, и не конфликтует с session_state."""
    if isinstance(default, float) or isinstance(step, float):
        lo, hi, step, default = float(lo), float(hi), float(step), float(default)
    else:
        lo, hi, step, default = int(lo), int(hi), int(step), int(default)
    lo, hi = min(lo, default), max(hi, default)
    kwargs = {} if key in st.session_state else {"value": default}
    return st.slider(label, min_value=lo, max_value=hi, step=step, key=key, help=help_text,
                     on_change=on_change, **kwargs)


def _checkbox(label, key, default, help_text, on_change=None):
    kwargs = {} if key in st.session_state else {"value": bool(default)}
    return st.checkbox(label, key=key, help=help_text, on_change=on_change, **kwargs)


def _expert_widget(spec, base_cfg, info, manual):
    """Виджет экспертной настройки. Значение попадает в ручные переопределения, только когда его меняют."""
    field, label, lo, hi, step, help_text = spec
    label, help_text = tr(label), tr(help_text)
    auto = info.get(field)
    if field in manual:
        current, tag, ver = manual[field], "вручную", "m"
    elif auto is not None:
        current, tag, ver = auto["value"], auto["source"], f"a{auto['value']}"
    else:
        current = getattr(base_cfg, field)
        tag = "config.yaml" if field in base_cfg.explicit_fields else ""
        ver = f"b{current}"
    key = f"x_{field}_{ver}"

    def _on_change():
        manual[field] = _typed(field, st.session_state[key])

    help_full = help_text
    if auto is not None:
        ceiling = auto["ceiling"]
        help_full += (tr("\n\n**Рассчитано MINT:** {auto}", auto=auto['auto'])
                      + (tr(" (потолок по лимитам моделей: {v})", v=max(0, ceiling)) if ceiling is not None else "") + ".")
    help_full += tr("\n\n**По умолчанию:** {v}.", v=getattr(DEFAULTS, field))
    shown = f"{label}" + (f" · {tr(tag)}" if tag else "")
    if lo is None:
        _checkbox(shown, key, current, help_full, on_change=_on_change)
    else:
        _slider(shown, key, lo, hi, step, current, help_full, on_change=_on_change)


def _reset_session_settings():
    st.session_state["mint_manual"] = {}
    st.session_state["mint_manual_limits"] = {}
    for k in list(st.session_state.keys()):
        if isinstance(k, str) and k.startswith(("x_", "lim_", "cfg_")):
            del st.session_state[k]


