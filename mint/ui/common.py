def render_audit_log_entry(entry):
    timing = section_timing(entry)
    if entry.get("kind") in ("focus", "checklist", "system"):
        title = point_title(entry)
    else:
        title = tr("⚙️ Лог проверки: Часть {part}/{total} -> «{preview}»", part=entry['part'], total=entry['total'],
                   preview=entry['preview'])
    with st.expander(title + (f" · ⏱ {timing}" if timing else "")):
        if entry["failed"]:
            st.error(entry["report"])
            return
        st.info(entry["report"])
        if entry["sources"]:
            st.caption(tr("Нормативные источники: ") + "; ".join(entry["sources"]))
        elif entry["no_norms"]:
            st.caption(tr("Нормативный контекст в базе не найден."))
        if entry["dropped"]:
            st.caption(tr("Отклонено: ") + " | ".join(entry["dropped"]))


def render_deep_log(entries):
    """Вопросы глубокой проверки одним списком: их десятки, по отдельному блоку на каждый — слишком много."""
    failed = sum(1 for e in entries if e["failed"])
    found = sum(len(e["findings"]) for e in entries)
    with st.expander(tr("🔬 Глубокая проверка: вопросов — {n}, замечаний — {f}, не выполнено — {x}", n=len(entries),
                        f=found, x=failed)):
        lines = []
        for e in entries:
            timing = section_timing(e)
            head = ("❌ " if e["failed"] else "") + f"**{e['title']}**" + (f" · ⏱ {timing}" if timing else "")
            body = e["report"] if e["failed"] or e["findings"] or e.get("claims") else tr("Часть чистая")
            lines.append(head + "  \n" + body.replace("\n", "  \n"))
        st.markdown("\n\n".join(lines))


def _width_kwargs(fn):
    """Растянуть элемент на всю ширину в любой версии Streamlit: width="stretch" (новые версии — у них width
    по умолчанию строка, а use_container_width устарел) или use_container_width (старые версии)."""
    try:
        params = inspect.signature(fn).parameters
    except (TypeError, ValueError):
        return {}
    width = params.get("width")
    if width is not None and isinstance(width.default, str):
        return {"width": "stretch"}
    if "use_container_width" in params:
        return {"use_container_width": True}
    if width is not None:
        return {"width": "stretch"}
    return {}


@st.cache_resource(show_spinner=False)
def _base_settings(signature, lang):
    """Настройки из .env и config.yaml; перечитываются, когда меняется config.yaml или .env.
    lang — язык сообщений о проблемах в config.yaml (кэш у каждого языка свой)."""
    with use_lang(lang):
        return load_settings()


def _conn_sig(cfg):
    """Отпечаток ключей и настроек TLS: после их исправления в .env кэш ответов серверов сбрасывается."""
    raw = "|".join([cfg.llm_api_key, cfg.embed_key, cfg.rerank_key, str(cfg.tls_verify)])
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


